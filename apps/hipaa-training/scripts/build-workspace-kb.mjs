#!/usr/bin/env node
/**
 * Compile SiyaOS KB topic markdown files into workspace-kb.generated.ts
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '../../..');
const kbRoot = path.join(repoRoot, 'docs/siyaos-knowledge-base');
const outFile = path.join(__dirname, '../src/content/workspace-kb.generated.ts');

function parseFrontmatter(raw) {
  const m = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
  if (!m) return null;
  const meta = {};
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^(\w[\w-]*):\s*(.*)$/);
    if (!kv) continue;
    const [, key, val] = kv;
    if (val === '') continue;
    if (val.startsWith('[')) continue;
    meta[key] = val.replace(/^["']|["']$/g, '');
  }
  let keywords = [];
  const kwBlock = m[1].match(/keywords:\s*\n((?:\s+-\s+.+\n?)+)/);
  if (kwBlock) {
    keywords = kwBlock[1]
      .split('\n')
      .map((l) => l.match(/^\s+-\s+(.+)$/))
      .filter(Boolean)
      .map((x) => x[1].trim());
  }
  let links = [];
  const linksSection = m[1].match(/links:\s*\n([\s\S]*?)(?=\n[A-Za-z_][\w-]*:|\n## |\n---|\n$)/);
  if (linksSection) {
    const block = linksSection[1];
    const labelMatches = [...block.matchAll(/label:\s*(.+)/g)];
    const hrefMatches = [...block.matchAll(/href:\s*(.+)/g)];
    for (let i = 0; i < Math.min(labelMatches.length, hrefMatches.length); i++) {
      links.push({
        label: labelMatches[i][1].trim(),
        href: hrefMatches[i][1].trim(),
      });
    }
  }
  return { meta, body: m[2], keywords, links };
}

function section(body, name) {
  const re = new RegExp(`## ${name}\\s*\\n+([\\s\\S]*?)(?=\\n## |$)`, 'i');
  const hit = body.match(re);
  return hit ? hit[1].trim() : '';
}

function compileBody(body, meta) {
  if (meta.kind === 'decision') {
    const decision = section(body, 'Decision');
    const reason = section(body, 'Reason');
    const ai = section(body, 'AI Context');
    return [ai, decision, reason].filter(Boolean).join(' ').replace(/\n+/g, ' ').trim();
  }
  if (meta.kind === 'principle') {
    const principle = section(body, 'Principle');
    const practice = section(body, 'In practice');
    const ai = section(body, 'AI Context');
    return [ai, principle, practice].filter(Boolean).join(' ').replace(/\n+/g, ' ').trim();
  }
  if (meta.kind === 'graveyard') {
    const stopped = section(body, 'Why we stopped');
    const ai = section(body, 'AI Context');
    const was = section(body, 'What it was');
    return [ai, was, stopped].filter(Boolean).join(' ').replace(/\n+/g, ' ').trim();
  }
  const ai = section(body, 'AI Context');
  const sop = section(body, 'SOP');
  const overview = section(body, 'Overview');
  const why = section(body, 'Why');
  const faq = section(body, 'FAQ');
  const trouble = section(body, 'Troubleshooting');
  const chunk = [overview, why, sop, faq, trouble, ai].filter(Boolean).join('\n\n');
  return chunk.replace(/\n+/g, ' ').replace(/\s+/g, ' ').trim().slice(0, 4500);
}

function collectMdFiles() {
  const topics = walkTopics(kbRoot);
  const decisionsDir = path.join(kbRoot, 'decisions');
  const decisions = fs.existsSync(decisionsDir)
    ? fs.readdirSync(decisionsDir).filter((f) => f.endsWith('.md')).map((f) => path.join(decisionsDir, f))
    : [];
  return [...topics, ...decisions];
}

function walkTopics(dir, acc = []) {
  if (!fs.existsSync(dir)) return acc;
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) walkTopics(p, acc);
    else if (ent.name.endsWith('.md') && dir.includes(`${path.sep}topics`)) acc.push(p);
  }
  return acc;
}

const files = collectMdFiles();
const entries = [];

for (const file of files) {
  const parsed = parseFrontmatter(fs.readFileSync(file, 'utf8'));
  if (!parsed) {
    console.warn('Skip (no frontmatter):', file);
    continue;
  }
  const { meta, body, keywords, links } = parsed;
  if (meta.status !== 'live') continue;
  if (meta.bot_retrieve === 'false' || meta.kind === 'idea') continue;
  if (!meta.id || !meta.title) {
    console.warn('Skip (missing id/title):', file);
    continue;
  }
  const module = meta.module || (meta.kind === 'decision' || meta.kind === 'principle' || meta.kind === 'graveyard' ? 'decisions' : null);
  if (!module) {
    console.warn('Skip (missing module):', file);
    continue;
  }
  entries.push({
    id: meta.id,
    category: module.replace(/^\d+-/, '').replace(/-/g, '_'),
    module,
    title: meta.title,
    keywords,
    body: compileBody(body, meta),
    links: links.length ? links : undefined,
    escalate: meta.escalate || undefined,
    priority: Number(meta.priority) || 1,
  });
}

entries.sort((a, b) => b.priority - a.priority);

const ts = `/* eslint-disable */
/** AUTO-GENERATED by scripts/build-workspace-kb.mjs — do not edit by hand */
import type { WorkspaceKbEntry } from "./workspace-kb.types";

export const GENERATED_WORKSPACE_KB: WorkspaceKbEntry[] = ${JSON.stringify(
  entries.map(({ priority, module, ...e }) => e),
  null,
  2
)};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, ts);
console.log(`Wrote ${entries.length} live topics → ${outFile}`);
